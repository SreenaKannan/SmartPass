package com.smartPass.smartpass.service;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.smartPass.smartpass.dto.*;
import com.smartPass.smartpass.entity.CommuterCard;
import com.smartPass.smartpass.entity.Payment;
import com.smartPass.smartpass.entity.User;
import com.smartPass.smartpass.repository.CommuterCardRepository;
import com.smartPass.smartpass.repository.PaymentRepository;
import com.smartPass.smartpass.repository.RenewalHistoryRepository;
import org.springframework.http.HttpStatus;
import org.springframework.stereotype.Service;
import org.springframework.web.server.ResponseStatusException;

import java.time.LocalDate;
import java.time.format.DateTimeParseException;
import java.time.temporal.ChronoUnit;
import java.util.ArrayList;
import java.util.List;

/**
 * SmartPass AI Hub - user-facing intelligent assistant.
 *
 * "Review My Application", "Explain My Status" and "Smart Recommendations"
 * are genuinely generated by a real LLM (Google Gemini) via {@link GeminiService} -
 * no hardcoded if/else copywriting. Real, verified facts (dates, counts,
 * risk flags already computed elsewhere in the app) are still pulled from
 * the database and handed to the model as grounding context, so it reasons
 * over true data instead of guessing or hallucinating numbers.
 *
 * "My SmartPass Insights" and "Smart Alerts" are left as exact factual
 * computations (counts, dates) rather than LLM output - those need to be
 * numerically exact, and running them through a model would only add
 * latency and hallucination risk for no benefit.
 */
@Service
public class AIHubService {

    private final CommuterCardRepository cardRepository;
    private final PaymentRepository paymentRepository;
    private final RenewalHistoryRepository renewalRepository;
    private final GeminiService geminiService;
    private final ObjectMapper objectMapper;

    public AIHubService(CommuterCardRepository cardRepository,
                         PaymentRepository paymentRepository,
                         RenewalHistoryRepository renewalRepository,
                         GeminiService geminiService,
                         ObjectMapper objectMapper) {
        this.cardRepository = cardRepository;
        this.paymentRepository = paymentRepository;
        this.renewalRepository = renewalRepository;
        this.geminiService = geminiService;
        this.objectMapper = objectMapper;
    }

    // ---------------------------------------------------------------
    // 1. Review My Application - real LLM call
    // ---------------------------------------------------------------
    public ReviewApplicationResponse analyzeApplicationData(ApplicationReviewRequest req) {
        String systemPrompt = "You are SmartPass's application review assistant for a public transit commuter-pass "
                + "system. You review a draft application BEFORE it is submitted and help the commuter fix problems. "
                + "Valid transportType values are exactly: Bus, Metro. "
                + "Valid passType values are exactly: Monthly, Quarterly, Half-Yearly, Yearly. "
                + "Flag any field that is missing, invalid, or inconsistent (e.g. identical source and destination). "
                + "Offer helpful, specific suggestions (e.g. cost-saving pass duration tips) when the data is otherwise fine. "
                + "Only use warnings for things that are unusual but not necessarily wrong. "
                + "Respond ONLY with strict JSON of the form: "
                + "{\"issues\": [string], \"suggestions\": [string], \"warnings\": [string], \"canProceed\": boolean}. "
                + "canProceed must be false whenever issues is non-empty.";

        var payload = objectMapper.createObjectNode();
        payload.put("sourceStation", nullToEmpty(req.getSourceStation()));
        payload.put("destinationStation", nullToEmpty(req.getDestinationStation()));
        payload.put("passType", nullToEmpty(req.getPassType()));
        payload.put("transportType", nullToEmpty(req.getTransportType()));

        String userPrompt = "Review this draft application:\n" + payload.toString();

        JsonNode result = callAndParse(systemPrompt, userPrompt);

        List<String> issues = toStringList(result.path("issues"));
        List<String> suggestions = toStringList(result.path("suggestions"));
        List<String> warnings = toStringList(result.path("warnings"));
        boolean canProceed = result.path("canProceed").asBoolean(issues.isEmpty());

        return new ReviewApplicationResponse(issues, suggestions, warnings, canProceed);
    }

    // ---------------------------------------------------------------
    // 2. Explain My Status - real LLM call, grounded in real DB facts
    // ---------------------------------------------------------------
    public StatusExplanationResponse explainApplicationStatus(CommuterCard card) {
        String status = card.getStatus() == null ? "UNKNOWN" : card.getStatus();

        List<String> completenessIssues = findCompletenessIssues(card);
        Integer queuePosition = "pending".equalsIgnoreCase(status) ? computeQueuePosition(card) : null;
        Long daysSinceApplied = card.getIssueDate() != null ? daysSince(card.getIssueDate()) : null;
        Long daysUntilExpiry = card.getExpiryDate() != null
                ? ChronoUnit.DAYS.between(LocalDate.now(), card.getExpiryDate())
                : null;

        String systemPrompt = "You are SmartPass's application-status assistant for a public transit commuter-pass "
                + "system. You are given REAL, VERIFIED facts about one commuter's application/pass. "
                + "Write a warm, plain-language explanation of their situation. "
                + "You MUST NOT invent any fact not given to you (no fake dates, no fake reasons, no fake queue numbers). "
                + "If a riskLevel of MEDIUM or HIGH is given, mention (without alarming the user or exposing internal scores) "
                + "that the application was flagged by automated verification for a closer look, and that this doesn't "
                + "necessarily mean something is wrong. "
                + "Respond ONLY with strict JSON of the form: "
                + "{\"explanation\": string, \"nextSteps\": string, \"reasons\": [string], \"actionItems\": [string]}.";

        var facts = objectMapper.createObjectNode();
        facts.put("status", status);
        facts.put("sourceStation", nullToEmpty(card.getSourceStation()));
        facts.put("destinationStation", nullToEmpty(card.getDestinationStation()));
        facts.put("passType", nullToEmpty(card.getPassType()));
        facts.put("transportType", nullToEmpty(card.getTransportType()));
        facts.put("issueDate", nullToEmpty(card.getIssueDate()));
        facts.put("expiryDate", card.getExpiryDate() != null ? card.getExpiryDate().toString() : null);
        facts.put("daysUntilExpiry", daysUntilExpiry);
        facts.put("daysSinceApplied", daysSinceApplied);
        facts.put("riskLevel", nullToEmpty(card.getRiskLevel()));
        facts.put("queuePosition", queuePosition);
        var completenessArray = objectMapper.createArrayNode();
        completenessIssues.forEach(completenessArray::add);
        facts.set("completenessIssuesFound", completenessArray);

        String userPrompt = "Here are the real facts about this application:\n" + facts.toString();

        JsonNode result = callAndParse(systemPrompt, userPrompt);

        String explanation = result.path("explanation").asText("");
        String nextSteps = result.path("nextSteps").asText("");
        List<String> reasons = toStringList(result.path("reasons"));
        List<String> actionItems = toStringList(result.path("actionItems"));

        return new StatusExplanationResponse(status, explanation, nextSteps, reasons, actionItems, queuePosition);
    }

    // ---------------------------------------------------------------
    // 3. Smart Recommendations - real LLM call, grounded in real DB facts
    // ---------------------------------------------------------------
    public RecommendationsResponse generateRecommendations(User user) {
        List<CommuterCard> cards = cardRepository.findByOwnerId(user.getId());
        List<Payment> payments = paymentRepository.findByUserId(user.getId());

        var cardsArray = objectMapper.createArrayNode();
        for (CommuterCard card : cards) {
            var c = objectMapper.createObjectNode();
            c.put("cardId", card.getCardId());
            c.put("status", nullToEmpty(card.getStatus()));
            c.put("sourceStation", nullToEmpty(card.getSourceStation()));
            c.put("destinationStation", nullToEmpty(card.getDestinationStation()));
            c.put("passType", nullToEmpty(card.getPassType()));
            if ("approved".equalsIgnoreCase(card.getStatus()) && card.getExpiryDate() != null) {
                c.put("daysUntilExpiry", ChronoUnit.DAYS.between(LocalDate.now(), card.getExpiryDate()));
            }
            cardsArray.add(c);
        }

        long failedPayments = payments.stream().filter(p -> "FAILED".equalsIgnoreCase(p.getStatus())).count();
        long successPayments = payments.stream().filter(p -> "SUCCESS".equalsIgnoreCase(p.getStatus())).count();

        var facts = objectMapper.createObjectNode();
        facts.set("cards", cardsArray);
        facts.put("failedPaymentCount", failedPayments);
        facts.put("successfulPaymentCount", successPayments);

        String systemPrompt = "You are SmartPass's personal travel assistant for a public transit commuter-pass system. "
                + "Given REAL facts about one commuter's cards and payments, generate a short, prioritized list of "
                + "genuinely useful, specific recommendations for them (e.g. renew soon, retry a failed payment, "
                + "reapply after rejection, consider a longer pass duration if they have multiple active cards). "
                + "Do not invent cards, dates or payments that are not in the facts. If there is nothing worth "
                + "recommending, return an empty list. "
                + "Respond ONLY with strict JSON of the form: "
                + "{\"recommendations\": [{\"title\": string, \"description\": string, \"priority\": integer (1=highest,5=lowest), "
                + "\"actionUrl\": string or null}]}.";

        String userPrompt = "Here are the real facts:\n" + facts.toString();

        JsonNode result = callAndParse(systemPrompt, userPrompt);

        List<RecommendationItem> recs = new ArrayList<>();
        JsonNode recArray = result.path("recommendations");
        if (recArray.isArray()) {
            for (JsonNode node : recArray) {
                recs.add(new RecommendationItem(
                        node.path("title").asText(""),
                        node.path("description").asText(""),
                        "AI_ASSISTED",
                        node.path("actionUrl").isNull() ? null : node.path("actionUrl").asText(null),
                        node.path("priority").asInt(3)));
            }
        }

        return new RecommendationsResponse(recs, true);
    }

    // ---------------------------------------------------------------
    // 4. My SmartPass Insights - exact factual computation (not AI)
    // ---------------------------------------------------------------
    public InsightsResponse generateInsights(User user) {
        List<CommuterCard> cards = cardRepository.findByOwnerId(user.getId());
        List<Payment> payments = paymentRepository.findByUserId(user.getId());

        int totalCards = cards.size();
        int activeCards = (int) cards.stream().filter(c -> "approved".equalsIgnoreCase(c.getStatus())).count();
        int pendingApplications = (int) cards.stream().filter(c -> "pending".equalsIgnoreCase(c.getStatus())).count();

        int completedRenewals = 0;
        for (CommuterCard card : cards) {
            completedRenewals += renewalRepository.findByCardId(card.getCardId()).size();
        }

        int totalSuccessfulPayments = (int) payments.stream()
                .filter(p -> "SUCCESS".equalsIgnoreCase(p.getStatus()))
                .count();

        LocalDate nextExpiryDate = cards.stream()
                .filter(c -> "approved".equalsIgnoreCase(c.getStatus()) && c.getExpiryDate() != null)
                .map(CommuterCard::getExpiryDate)
                .min(LocalDate::compareTo)
                .orElse(null);

        String applicationStatus;
        String nextImportantAction;
        if (totalCards == 0) {
            applicationStatus = "No Applications";
            nextImportantAction = "Apply for your first SmartPass to get started.";
        } else if (pendingApplications > 0) {
            applicationStatus = "Pending Review";
            nextImportantAction = "Wait for admin review on your pending application(s).";
        } else if (activeCards > 0) {
            applicationStatus = "Active";
            nextImportantAction = nextExpiryDate != null
                    ? "Your next pass expires on " + nextExpiryDate + ". Plan your renewal ahead of time."
                    : "Keep enjoying your active pass.";
        } else {
            applicationStatus = "No Active Pass";
            nextImportantAction = "Apply for a new pass or check the status of a previous application.";
        }

        return new InsightsResponse(totalCards, activeCards, completedRenewals, pendingApplications,
                applicationStatus, nextImportantAction, nextExpiryDate, totalSuccessfulPayments);
    }

    // ---------------------------------------------------------------
    // 5. Smart Alerts - exact factual computation (not AI)
    // ---------------------------------------------------------------
    public AlertsResponse generateAlerts(User user) {
        List<SmartAlert> alerts = new ArrayList<>();
        List<CommuterCard> cards = cardRepository.findByOwnerId(user.getId());
        List<Payment> payments = paymentRepository.findByUserId(user.getId());
        var now = java.time.LocalDateTime.now();

        for (CommuterCard card : cards) {
            if ("approved".equalsIgnoreCase(card.getStatus()) && card.getExpiryDate() != null) {
                long daysLeft = ChronoUnit.DAYS.between(LocalDate.now(), card.getExpiryDate());
                if (daysLeft >= 0 && daysLeft <= 2) {
                    alerts.add(new SmartAlert("HIGH",
                            "Your pass (" + card.getSourceStation() + " → " + card.getDestinationStation()
                                    + ") expires in " + daysLeft + " day(s). Renew now to avoid disruption.",
                            "/mycards", now, "EXPIRY"));
                } else if (daysLeft > 2 && daysLeft <= 7) {
                    alerts.add(new SmartAlert("MEDIUM",
                            "Your pass (" + card.getSourceStation() + " → " + card.getDestinationStation()
                                    + ") expires in " + daysLeft + " day(s). Consider renewing soon.",
                            "/mycards", now, "EXPIRY"));
                }
            }

            if ("pending".equalsIgnoreCase(card.getStatus()) && card.getIssueDate() != null) {
                long daysSinceApplied = daysSince(card.getIssueDate());
                if (daysSinceApplied > 7) {
                    alerts.add(new SmartAlert("MEDIUM",
                            "Your application (" + card.getSourceStation() + " → " + card.getDestinationStation()
                                    + ") has been pending for " + daysSinceApplied + " days. You may want to contact support.",
                            "/mycards", now, "APPLICATION"));
                }
            }
        }

        boolean hasFailedPayment = payments.stream().anyMatch(p -> "FAILED".equalsIgnoreCase(p.getStatus()));
        if (hasFailedPayment) {
            alerts.add(new SmartAlert("HIGH",
                    "A recent payment failed. Please retry it to keep your pass active.",
                    "/payment", now, "PAYMENT"));
        }

        boolean hasRecentSuccess = payments.stream().anyMatch(p -> "SUCCESS".equalsIgnoreCase(p.getStatus()));
        if (hasRecentSuccess && !hasFailedPayment) {
            alerts.add(new SmartAlert("LOW",
                    "Your most recent payment was successful. No action needed.",
                    "/payment", now, "PAYMENT"));
        }

        alerts.sort(java.util.Comparator.comparingInt(a -> priorityRank(a.getPriority())));
        return new AlertsResponse(alerts);
    }

    // ---------------------------------------------------------------
    // Helpers
    // ---------------------------------------------------------------
    private JsonNode callAndParse(String systemPrompt, String userPrompt) {
        String rawJson = geminiService.chatJson(systemPrompt, userPrompt);
        try {
            return objectMapper.readTree(rawJson);
        } catch (Exception e) {
            throw new ResponseStatusException(HttpStatus.BAD_GATEWAY, "AI response could not be parsed.", e);
        }
    }

    private List<String> toStringList(JsonNode arrayNode) {
        List<String> list = new ArrayList<>();
        if (arrayNode != null && arrayNode.isArray()) {
            for (JsonNode node : arrayNode) {
                list.add(node.asText());
            }
        }
        return list;
    }

    private int priorityRank(String priority) {
        if ("HIGH".equalsIgnoreCase(priority)) return 0;
        if ("MEDIUM".equalsIgnoreCase(priority)) return 1;
        return 2;
    }

    private long daysSince(String isoDate) {
        try {
            LocalDate date = LocalDate.parse(isoDate);
            return ChronoUnit.DAYS.between(date, LocalDate.now());
        } catch (DateTimeParseException e) {
            return 0;
        }
    }

    /**
     * Real, checkable data-completeness facts on an already-submitted card,
     * handed to the model as grounding context (the model does not invent these).
     */
    private List<String> findCompletenessIssues(CommuterCard card) {
        List<String> issues = new ArrayList<>();
        if (isBlank(card.getSourceStation())) issues.add("Source station is missing.");
        if (isBlank(card.getDestinationStation())) issues.add("Destination station is missing.");
        if (!isBlank(card.getSourceStation()) && !isBlank(card.getDestinationStation())
                && card.getSourceStation().equalsIgnoreCase(card.getDestinationStation())) {
            issues.add("Source and destination stations are the same.");
        }
        if (isBlank(card.getPassType())) issues.add("Pass type is missing.");
        if (isBlank(card.getTransportType())) issues.add("Transport type is missing.");
        return issues;
    }

    private Integer computeQueuePosition(CommuterCard card) {
        if (card.getIssueDate() == null) return null;
        List<CommuterCard> pending = cardRepository.findByStatus("Pending");
        long aheadCount = pending.stream()
                .filter(c -> !c.getCardId().equals(card.getCardId()))
                .filter(c -> isEarlier(c, card))
                .count();
        return (int) aheadCount;
    }

    private boolean isEarlier(CommuterCard a, CommuterCard b) {
        if (a.getIssueDate() == null || b.getIssueDate() == null) return false;
        int cmp = a.getIssueDate().compareTo(b.getIssueDate());
        if (cmp != 0) return cmp < 0;
        return a.getCardId() < b.getCardId();
    }

    private boolean isBlank(String s) {
        return s == null || s.trim().isEmpty();
    }

    private String nullToEmpty(String s) {
        return s == null ? "" : s;
    }
}
